import { isAbsolute, join } from "node:path"
import { TankError } from "@shoalwork/contracts"
import { Tank, type TankContext } from "@shoalwork/tank"
import { Effect, Option } from "effect"
import { type Briefing, renderBriefing } from "./briefing.js"

export const AGENTS_FILE = "AGENTS.md"
export const CLAUDE_FILE = "CLAUDE.md"
// Written instead of AGENTS.md when the repo has instructions of its own (they are never overwritten).
export const GENERATED_FILE = "AGENTS.generated.md"
const GENERATED_FILES: ReadonlyArray<string> = [AGENTS_FILE, CLAUDE_FILE, GENERATED_FILE]
// First line of every file this module writes: it is how a later call (a retry, a removal) tells ours from the repo's.
export const MARKER = "<!-- generated by shoalwork for one run: do not commit -->"
const CLAUDE_STUB = "@AGENTS.md\n"

// Appends the names given as argv to the file in $1, once each. The script is constant; nothing is interpolated.
const APPEND_ONCE =
  'target="$1"; shift; mkdir -p "$(dirname "$target")" && touch "$target" && ' +
  'for line in "$@"; do grep -qxF "$line" "$target" || printf \'%s\\n\' "$line" >> "$target"; done'

const readOptional = (ctx: TankContext, rel: string) =>
  Effect.gen(function* () {
    const tank = yield* Tank
    return yield* tank.readFile(ctx, rel).pipe(
      Effect.map(Option.some),
      Effect.catch(() => Effect.succeed(Option.none<string>())),
    )
  })

// Keeps the generated files out of `git add -A` through the repo's info/exclude (shared by the worktrees of one clone).
// A directory that is not a git worktree has nothing to keep out.
export const keepOutOfGit = (ctx: TankContext): Effect.Effect<void, TankError, Tank> =>
  Effect.gen(function* () {
    const tank = yield* Tank
    const found = yield* tank.exec(ctx, ["git", "rev-parse", "--git-path", "info/exclude"])
    const raw = found.stdout.trim()
    if (found.exitCode !== 0 || raw === "") return
    const target = isAbsolute(raw) ? raw : join(ctx.cwd, raw)
    const appended = yield* tank.exec(ctx, ["sh", "-c", APPEND_ONCE, "sh", target, ...GENERATED_FILES])
    if (appended.exitCode !== 0) {
      return yield* Effect.fail(
        new TankError({ op: "exclude", cause: appended.stderr.trim() || "append failed" }),
      )
    }
  })

// A free name counts as ours for a write; a name that is absent does not match for a removal.
const freeOrOurs = (text: Option.Option<string>, accept: (value: string) => boolean): boolean =>
  Option.match(text, { onNone: () => true, onSome: accept })
const isOurs = (text: Option.Option<string>, accept: (value: string) => boolean): boolean =>
  Option.match(text, { onNone: () => false, onSome: accept })

// Writes the briefing into the worktree. The pair AGENTS.md + CLAUDE.md (a stub that imports it) is written when both
// names are free or already ours; otherwise the repo has instructions of its own and the briefing goes to
// AGENTS.generated.md, and the caller passes it to the executor (conflict: true).
export const writeInstructionFiles = (
  ctx: TankContext,
  briefing: Briefing,
): Effect.Effect<{ readonly conflict: boolean }, TankError, Tank> =>
  Effect.gen(function* () {
    const tank = yield* Tank
    const agents = yield* readOptional(ctx, AGENTS_FILE)
    const claude = yield* readOptional(ctx, CLAUDE_FILE)
    yield* keepOutOfGit(ctx)
    const body = `${MARKER}\n${renderBriefing(briefing)}`
    const agentsOurs = freeOrOurs(agents, (text) => text.startsWith(MARKER))
    // A CLAUDE.md stub is ours only next to our AGENTS.md: a repo that tracks the same stub alone keeps it.
    const pairOurs =
      agentsOurs &&
      freeOrOurs(claude, (text) => text === CLAUDE_STUB) &&
      (Option.isSome(agents) || Option.isNone(claude))
    if (pairOurs) {
      yield* tank.writeFile(ctx, AGENTS_FILE, body)
      if (Option.isNone(claude)) yield* tank.writeFile(ctx, CLAUDE_FILE, CLAUDE_STUB)
      return { conflict: false }
    }
    const generated = yield* readOptional(ctx, GENERATED_FILE)
    if (!freeOrOurs(generated, (text) => text.startsWith(MARKER))) {
      return yield* Effect.fail(
        new TankError({ op: "writeFile", cause: `${GENERATED_FILE} is the repo's own file` }),
      )
    }
    yield* tank.writeFile(ctx, GENERATED_FILE, body)
    return { conflict: true }
  })

// Removes what writeInstructionFiles wrote (matched by the marker or the stub), never a file of the repo.
export const removeInstructionFiles = (ctx: TankContext): Effect.Effect<void, TankError, Tank> =>
  Effect.gen(function* () {
    const tank = yield* Tank
    const agents = yield* readOptional(ctx, AGENTS_FILE)
    const claude = yield* readOptional(ctx, CLAUDE_FILE)
    const generated = yield* readOptional(ctx, GENERATED_FILE)
    const doomed: Array<string> = []
    if (isOurs(agents, (text) => text.startsWith(MARKER))) {
      doomed.push(AGENTS_FILE)
      if (isOurs(claude, (text) => text === CLAUDE_STUB)) doomed.push(CLAUDE_FILE)
    }
    if (isOurs(generated, (text) => text.startsWith(MARKER))) doomed.push(GENERATED_FILE)
    if (doomed.length === 0) return
    const removed = yield* tank.exec(ctx, ["rm", "-f", "--", ...doomed])
    if (removed.exitCode !== 0) {
      return yield* Effect.fail(new TankError({ op: "removeInstructionFiles", cause: removed.stderr.trim() }))
    }
  })
